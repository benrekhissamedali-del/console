function createXInputMappings(): Record<PSButtonId, ButtonMapping> {
  const result = {} as Record<PSButtonId, ButtonMapping>;
  for (const btn of PS_BUTTON_CATALOG) {
    result[btn.id] = {
      buttonId: btn.id,
      outputType: btn.id === 'mute' ? 'keyboard' : 'xinput',
      primaryValue: btn.id === 'mute' ? 'M' : btn.defaultXInput,
      modifiers: [],
      behavior: 'press',
      turboRateMs: 80,
      label: btn.id === 'mute' ? 'Discord Mute' : `Xbox ${btn.defaultXInput}`,
    };
  }
  return result;
}

