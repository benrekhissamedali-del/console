export function formatMappingSummary(mapping: ButtonMapping): string {
  if (mapping.outputType === 'unbound') return 'Unbound';
  if (mapping.outputType === 'macro') {
    return mapping.primaryValue ? `Macro: ${mapping.primaryValue}` : 'Macro (Empty)';
  }
  const mods = mapping.modifiers.length > 0 ? `${mapping.modifiers.join(' + ')} + ` : '';
  return `${mods}${mapping.primaryValue}`;
}
